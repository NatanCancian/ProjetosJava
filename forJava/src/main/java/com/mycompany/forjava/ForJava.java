package com.mycompany.forjava;
public class ForJava {

    public static void main(String[] args) {
                
        for(int i = 10; i >= 0; i--){
            System.out.println(i);
        }
        System.out.println("FELIZ ANO NOVO!");
        // For executa o loop um número limitado de vezes, 
        // definido nos parâmetros
        /* para incrementos ou decrementos maior que usa-se
           +=10, ou -=10 (o salto será de 10 em 10)*/
    }
}
